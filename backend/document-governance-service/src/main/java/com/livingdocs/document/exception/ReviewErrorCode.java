@Getter
@RequiredArgsConstructor
public enum ReviewErrorCode {
    METHOD_NOT_ALLOWED("METHOD_NOT_ALLOWED", HttpStatus.METHOD_NOT_ALLOWED),
    NOT_ACCEPTABLE("NOT_ACCEPTABLE", HttpStatus.NOT_ACCEPTABLE),
    UNSUPPORTED_MEDIA_TYPE("UNSUPPORTED_MEDIA_TYPE", HttpStatus.UNSUPPORTED_MEDIA_TYPE),
    INVALID_REQUEST("INVALID_REQUEST", HttpStatus.BAD_REQUEST),
    INVALID_IF_MATCH("INVALID_IF_MATCH", HttpStatus.BAD_REQUEST),
    PRECONDITION_REQUIRED("PRECONDITION_REQUIRED", HttpStatus.PRECONDITION_REQUIRED),
    UNAUTHENTICATED("UNAUTHENTICATED", HttpStatus.UNAUTHORIZED),
    REVIEW_FORBIDDEN("REVIEW_FORBIDDEN", HttpStatus.FORBIDDEN),
    DOCUMENT_VERSION_NOT_FOUND("DOCUMENT_VERSION_NOT_FOUND", HttpStatus.NOT_FOUND),
    STATE_TRANSITION_FORBIDDEN("STATE_TRANSITION_FORBIDDEN", HttpStatus.CONFLICT),
    REVISION_CONFLICT("REVISION_CONFLICT", HttpStatus.PRECONDITION_FAILED),
    IDEMPOTENCY_CONFLICT("IDEMPOTENCY_CONFLICT", HttpStatus.CONFLICT),
    REPLAY_SNAPSHOT_UNAVAILABLE("REPLAY_SNAPSHOT_UNAVAILABLE", HttpStatus.CONFLICT),
    RETURN_REASON_REQUIRED("RETURN_REASON_REQUIRED", HttpStatus.UNPROCESSABLE_ENTITY),
    REVIEW_EVIDENCE_REQUIRED("REVIEW_EVIDENCE_REQUIRED", HttpStatus.UNPROCESSABLE_ENTITY),
    REVIEW_EVIDENCE_INVALID("REVIEW_EVIDENCE_INVALID", HttpStatus.UNPROCESSABLE_ENTITY),
    SOURCE_EVIDENCE_INSUFFICIENT("SOURCE_EVIDENCE_INSUFFICIENT", HttpStatus.UNPROCESSABLE_ENTITY),
    EVIDENCE_LIMIT_EXCEEDED("EVIDENCE_LIMIT_EXCEEDED", HttpStatus.UNPROCESSABLE_ENTITY),
    DUPLICATE_EVIDENCE("DUPLICATE_EVIDENCE", HttpStatus.UNPROCESSABLE_ENTITY),
    SOURCE_CHANGED_REVALIDATION_REQUIRED("SOURCE_CHANGED_REVALIDATION_REQUIRED", HttpStatus.CONFLICT),
    SOURCE_VALIDATION_UNAVAILABLE("SOURCE_VALIDATION_UNAVAILABLE", HttpStatus.SERVICE_UNAVAILABLE),
    CONCURRENT_REVIEW("CONCURRENT_REVIEW", HttpStatus.CONFLICT),
    PERSISTENCE_ERROR("PERSISTENCE_ERROR", HttpStatus.INTERNAL_SERVER_ERROR);

    private final String wireCode;
    private final HttpStatus status;
}
